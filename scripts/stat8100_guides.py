"""Student guidance, navigation metadata and reporting templates for STAT 8100."""

GUIDES = {}


def learning_points(what, concept, code_need, action, code_text, output,
                    important, interpretation, reporting, mistakes):
    return [
        f"What is being asked? {what}",
        f"Statistical concept: {concept}",
        f"Do you need to write code? {code_need}",
        f"What to do in Jupyter: {action}",
        f"Code to use: {code_text}",
        f"Output to inspect: {output}",
        f"Important values or observations: {important}",
        f"How to interpret it: {interpretation}",
        f"What to report: {reporting}",
        f"Common mistakes to avoid: {mistakes}",
    ]


def add(qid, title, requirement, classification, jupyter_action, code_required,
        points, output_to_inspect, interpretation_guidance, reporting_guidance,
        common_mistakes):
    GUIDES[qid] = {
        "id": qid,
        "title": title,
        "requirement": requirement,
        "classification": classification,
        "jupyter_action": jupyter_action,
        "code_required": code_required,
        "learning": points,
        "output_to_inspect": output_to_inspect,
        "interpretation": interpretation_guidance,
        "reporting": reporting_guidance,
        "common_mistakes": common_mistakes,
    }


